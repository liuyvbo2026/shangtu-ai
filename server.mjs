import http from 'node:http';
import { readFile, stat } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('.', import.meta.url));
// Same origin API; only explicitly public frontend resources are served.
import {createRuntime,loadConfig} from './backend/integration/runtime.mjs';
import {loadApiKey,loadMimoKey} from './backend/integration/credentials.mjs';
import {staticHandler} from './backend/integration/static.mjs';
import {createApiSettings} from './backend/integration/api-settings.mjs';
const config=loadConfig(root);
const apiSettings=createApiSettings({root,fallback:{image:loadApiKey(root),text:loadMimoKey(root)}});
const runtime=createRuntime({dataDir:path.resolve(process.env.AIGC_DATA_DIR||path.join(root,'.private','single-product')),config,apiSettings});
const serveStatic=staticHandler(root);
const port=Number(process.env.PORT||5178);
const server=http.createServer((req,res)=>req.url.startsWith('/api/')?runtime.handler(req,res):serveStatic(req,res));
server.requestTimeout=60000;server.headersTimeout=15000;
server.on('error',async()=>{await runtime.close();console.error('本地服务启动失败，请检查端口及私有目录权限。');process.exitCode=1;});
server.listen(port,'127.0.0.1',()=>console.log(`商图AI: http://127.0.0.1:${server.address().port} (${runtime.status().mode})`));
let closing=false;
for(const signal of ['SIGINT','SIGTERM'])process.on(signal,async()=>{if(closing)return;closing=true;server.close();await runtime.close();process.exit(0);});
